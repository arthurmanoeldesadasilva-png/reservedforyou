function getAmbientState() {
  return localStorage.getItem("ninaAmbientOn") === "1";
}

function setAmbientState(on) {
  localStorage.setItem("ninaAmbientOn", on ? "1" : "0");
}

function getSoundMode() {
  return localStorage.getItem("ninaSoundMode") || "ambient";
}

function setSoundMode(mode) {
  localStorage.setItem("ninaSoundMode", mode);
}

function getLang() {
  return localStorage.getItem("ninaLang") || "en";
}

function setLang(lang) {
  localStorage.setItem("ninaLang", lang);
}

function applyLanguage(lang) {
  const dict = translations[lang] || translations.en;
  document.documentElement.lang = lang === "pt" ? "pt" : "en";

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    if (dict[key]) el.textContent = dict[key];
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.dataset.i18nPlaceholder;
    if (dict[key]) el.setAttribute("placeholder", dict[key]);
  });

  updateAudioButtonLabel(dict);
  updateBreathingButtonLabel(dict);
}

function updateAudioButtonLabel(dict) {
  const audioBtn = document.getElementById("audioToggle");
  if (!audioBtn) return;
  audioBtn.textContent = ambientOn ? dict.audioToggleOn : dict.audioToggleOff;
}

function initAmbientToggle() {
  const audioBtn = document.getElementById("audioToggle");
  const soundSelect = document.getElementById("soundSelect");
  if (!audioBtn) return;

  ambientOn = getAmbientState();
  currentSoundMode = getSoundMode();

  // Garante que o elemento de áudio seja criado ou limpo corretamente
  if (!audioElement) {
    audioElement = new Audio();
    audioElement.loop = true;
    audioElement.volume = 0.5;
  }

  if (soundSelect) {
    soundSelect.value = currentSoundMode;

    // Remove qualquer listener antigo para não duplicar eventos
    soundSelect.onchange = null;

    soundSelect.addEventListener("change", (e) => {
      currentSoundMode = e.target.value;
      setSoundMode(currentSoundMode);

      const filePath = soundFilesMap[currentSoundMode] || soundFilesMap.ambient;

      // Para o som atual imediatamente e reseta o tempo ao trocar de música
      audioElement.pause();
      audioElement.currentTime = 0;
      sessionStorage.removeItem("musicTime"); // Limpa o tempo salvo para não conflitar

      // Atribui o novo arquivo e carrega
      audioElement.src = filePath;
      audioElement.load();

      // Se o som estiver ligado, toca o novo arquivo
      if (ambientOn) {
        audioElement.play().catch(err => console.log("Erro ao tocar áudio:", err));
      }
    });
  }

  // Configuração inicial do arquivo ao carregar a página
  const initialPath = soundFilesMap[currentSoundMode] || soundFilesMap.ambient;
  
  if (!audioElement.src.endsWith(initialPath)) {
    audioElement.src = initialPath;
  }

  // Recupera o tempo salvo da página anterior, aplica e limpa em seguida
  const savedTime = sessionStorage.getItem("musicTime");
  if (savedTime) {
    audioElement.currentTime = parseFloat(savedTime);
    sessionStorage.removeItem("musicTime");
  }

  if (ambientOn) {
    audioElement.play().catch(err => console.log("Erro ao tocar áudio:", err));
  }

  // Remove listener antigo do botão para evitar conflitos
  audioBtn.onclick = null;

  audioBtn.addEventListener("click", () => {
    ambientOn = !ambientOn;
    setAmbientState(ambientOn);

    if (ambientOn) {
      // Garante que pega a música correta selecionada no momento de ligar
      const activePath = soundFilesMap[soundSelect ? soundSelect.value : currentSoundMode] || soundFilesMap.ambient;
      if (!audioElement.src.endsWith(activePath)) {
        audioElement.src = activePath;
        audioElement.load();
      }
      audioElement.play().catch(err => console.log("Erro ao tocar áudio:", err));
    } else {
      audioElement.pause();
    }

    const lang = getLang();
    updateAudioButtonLabel(translations[lang] || translations.en);
  });
}

